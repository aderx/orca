#!/usr/bin/env node
// Local development bundle: compiled checkout + isolated Electron identity and profile.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { buildSync } from 'esbuild';

if (process.platform !== 'darwin' || process.arch !== 'arm64') throw new Error('This local packaging helper targets macOS arm64');
const repo = path.resolve(import.meta.dirname, '../..');
const destination = path.resolve(process.argv[2] || path.join(repo, 'dist/zstack-dev'));
const app = path.join(destination, 'Orca ZStack Dev.app');
const profile = path.join(os.homedir(), 'Library/Application Support/Orca ZStack Dev');
const plugin = path.join(repo, 'plugins/zstack-launcher');
const { version, buildVersion } = JSON.parse(fs.readFileSync(path.join(repo, 'package.json'), 'utf8'));
const quote = value => `'${value.replaceAll("'", "'\\''")}'`;
if (!fs.existsSync(path.join(repo, 'out/main/index.js')) || !fs.existsSync(path.join(repo, 'out/renderer/index.html'))) throw new Error('Run build:electron-vite first');
if (fs.existsSync(app)) throw new Error(`Build target already exists: ${app}; choose a fresh destination`);
fs.mkdirSync(destination, { recursive: true });
execFileSync('/usr/bin/ditto', [path.join(repo, 'node_modules/electron/dist/Electron.app'), app]);
const plist = path.join(app, 'Contents/Info.plist');
for (const [key, value] of Object.entries({ CFBundleIdentifier: 'local.orca.zstack.dev', CFBundleName: 'Orca ZStack Dev', CFBundleDisplayName: 'Orca ZStack Dev', CFBundleExecutable: 'OrcaZStackDev', CFBundleShortVersionString: version, CFBundleVersion: buildVersion || version })) {
  execFileSync('/usr/bin/plutil', ['-replace', key, '-string', value, plist]);
}
const executable = path.join(app, 'Contents/MacOS/OrcaZStackDev');
fs.writeFileSync(executable, `#!/bin/sh\nset -eu\nunset ELECTRON_RUN_AS_NODE\nexport ORCA_DEV_USER_DATA_PATH=${quote(profile)}\nexport ORCA_DEV_INSTANCE_KEY=orca-zstack-dev\nexport ORCA_DEV_INSTANCE_LABEL='ZStack Launcher Dev'\nexport ORCA_DEV_DOCK_TITLE='Orca ZStack Dev'\nexport ORCA_DEV_REPO_ROOT=${quote(repo)}\nexport PATH=${quote(process.env.PATH || '/usr/bin:/bin')}\ncd ${quote(repo)}\nexec "$(dirname "$0")/Electron" ${quote(repo)} "$@"\n`, { mode: 0o755 });
// A default state generated by the current source avoids importing production account data.
const bootstrap = path.join(repo, 'out/zstack-dev-bootstrap.cjs');
buildSync({ stdin: { contents: `export { getDefaultPersistedState } from './src/shared/constants'; export { fingerprintPluginConsent } from './src/shared/plugins/plugin-consent-fingerprint';`, resolveDir: repo, loader: 'ts' }, outfile: bootstrap, bundle: true, platform: 'node', format: 'cjs' });
const require = createRequire(import.meta.url);
const { getDefaultPersistedState, fingerprintPluginConsent } = require(bootstrap);
const stateFile = path.join(profile, 'orca-data.json');
fs.mkdirSync(profile, { recursive: true });
if (!fs.existsSync(stateFile)) {
  const state = getDefaultPersistedState(os.homedir());
  state.settings.pluginSystemEnabled = true;
  state.settings.devPluginPaths = [plugin];
  state.settings.pluginConsents = { 'local.zstack-launcher': fingerprintPluginConsent(JSON.parse(fs.readFileSync(path.join(plugin, 'orca-plugin.json'), 'utf8'))) };
  state.settings.defaultTuiAgent = 'blank';
  fs.writeFileSync(stateFile, JSON.stringify(state, null, 2), { mode: 0o600 });
}
execFileSync('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', app], { stdio: 'inherit' });
execFileSync('/usr/bin/codesign', ['--verify', '--deep', '--strict', app], { stdio: 'inherit' });
fs.writeFileSync(path.join(destination, 'BUILD-INFO.json'), JSON.stringify({ app, repo, profile, plugin, version, buildVersion, builtAt: new Date().toISOString(), type: 'local-development-checkout', arch: process.arch }, null, 2));
console.log(`Built: ${app}\nProfile: ${profile}\nThis development app uses the compiled checkout at ${repo}.`);
